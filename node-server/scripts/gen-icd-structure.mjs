#!/usr/bin/env node
/**
 * Generate the static ICD-10 structure tables used by the admin terminology
 * explorer (node-server/src/data/*.json). Neither the CMS order file nor the
 * Taiwan xlsx carries chapters / blocks / 7th-character definitions / PCS axis
 * labels, so they are extracted once from the public-domain CMS releases:
 *
 *   node scripts/gen-icd-structure.mjs \
 *     icd10cm_tabular_2026.xml icd10pcs_tables_2026.xml src/data
 *
 * Inputs: "Code Tables, Tabular and Index" (ICD-10-CM) and
 * "ICD-10-PCS Code Tables and Index" zips from cms.gov.
 * Regex-based on purpose (no XML dependency): both files are machine-generated
 * and well-formed.
 */
import fs from "node:fs";
import path from "node:path";

const [cmXmlPath, pcsXmlPath, outDir] = process.argv.slice(2);
if (!cmXmlPath || !pcsXmlPath || !outDir) {
  console.error("usage: gen-icd-structure.mjs <cm-tabular.xml> <pcs-tables.xml> <outDir>");
  process.exit(2);
}

/**
 * Emit the data as a TS module holding one JSON string literal: tsc copies it
 * into dist/ like any source file (no asset step) and does not try to infer a
 * type for a megabyte of JSON. Parsed lazily at runtime.
 */
function writeDataModule(file, name, value) {
  const header = `// GENERATED by scripts/gen-icd-structure.mjs from ${value.source} - do not edit.\n`;
  fs.writeFileSync(path.join(outDir, file), `${header}export const ${name}: string = ${JSON.stringify(JSON.stringify(value))};\n`);
}

const decode = (s) =>
  s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();

// ── ICD-10-CM: chapters → sections → categories, plus 7th-character defs ──
const cm = fs.readFileSync(cmXmlPath, "utf8");
const version = /<version>([^<]+)<\/version>/.exec(cm)?.[1] ?? "";
const chapters = [];
for (const chm of cm.matchAll(/<chapter>([\s\S]*?)\n  <\/chapter>/g)) {
  const body = chm[1];
  const num = Number(/<name>(\d+)<\/name>/.exec(body)[1]);
  const descRaw = decode(/<desc>([\s\S]*?)<\/desc>/.exec(body)[1]);
  const rm = /\(([A-Z0-9]{3})-([A-Z0-9]{3})\)\s*$/.exec(descRaw);
  const title = descRaw.replace(/\s*\([A-Z0-9]{3}-[A-Z0-9]{3}\)\s*$/, "");
  const sections = [];
  for (const sm of body.matchAll(/\n    <section id="([^"]+)">([\s\S]*?)\n    <\/section>/g)) {
    const sbody = sm[2];
    const sdesc = decode(/<desc>([\s\S]*?)<\/desc>/.exec(sbody)?.[1] ?? sm[1]).replace(/\s*\([A-Z0-9]{3}-[A-Z0-9]{3}\)\s*$/, "");
    // Categories = <diag> directly under the section (6-space indent).
    const cats = [...sbody.matchAll(/\n      <diag>\s*<name>([A-Z0-9]{3})<\/name>/g)].map((m) => m[1]);
    const [first, last] = sm[1].includes("-") ? sm[1].split("-") : [sm[1], sm[1]];
    sections.push({ id: sm[1], title: sdesc, first, last, cats });
  }
  chapters.push({ num, title, first: rm?.[1] ?? sections[0]?.first, last: rm?.[2] ?? sections.at(-1)?.last, sections });
}

// 7th characters: <sevenChrDef> belongs to the enclosing <diag>; extract by
// walking diag open/close tags with a stack.
const sevenChr = {};
{
  const stack = [];
  const re = /<diag>|<\/diag>|<name>([^<]+)<\/name>|<sevenChrDef>([\s\S]*?)<\/sevenChrDef>/g;
  let expectName = false;
  for (const m of cm.matchAll(re)) {
    if (m[0] === "<diag>") {
      stack.push(null);
      expectName = true;
    } else if (m[0] === "</diag>") {
      stack.pop();
    } else if (m[1] !== undefined) {
      if (expectName && stack.length) stack[stack.length - 1] = m[1];
      expectName = false;
    } else if (m[2] !== undefined && stack.length) {
      const code = stack[stack.length - 1];
      const defs = {};
      for (const e of m[2].matchAll(/<extension char="([^"]+)">([\s\S]*?)<\/extension>/g)) defs[e[1]] = decode(e[2]);
      if (code) sevenChr[code] = defs;
    }
  }
}

writeDataModule("icd10cmStructure.data.ts", "ICD10CM_STRUCTURE_JSON", { source: `CMS ICD-10-CM tabular ${version}`, chapters, seventh: sevenChr });

// ── ICD-10-PCS: one entry per table (first 3 characters) ──
const pcs = fs.readFileSync(pcsXmlPath, "utf8");
const pcsVersion = /<version>([^<]+)<\/version>/.exec(pcs)?.[1] ?? "";
const axisRe = /<axis pos="(\d)"[^>]*>\s*<title>([^<]*)<\/title>([\s\S]*?)<\/axis>/g;
const labels = (body) => [...body.matchAll(/<label code="([^"]+)">([\s\S]*?)<\/label>/g)].map((m) => [m[1], decode(m[2])]);
const tables = {};
for (const tm of pcs.matchAll(/<pcsTable>([\s\S]*?)<\/pcsTable>/g)) {
  const body = tm[1];
  const head = body.split("<pcsRow")[0];
  const titles = ["", "", "", "", "", "", ""];
  const headAxes = {};
  let definition = "";
  for (const a of head.matchAll(axisRe)) {
    const pos = Number(a[1]);
    titles[pos - 1] = decode(a[2]);
    headAxes[pos] = labels(a[3])[0];
    const d = /<definition>([\s\S]*?)<\/definition>/.exec(a[3]);
    if (pos === 3 && d) definition = decode(d[1]);
  }
  const key = headAxes[1][0] + headAxes[2][0] + headAxes[3][0];
  const rows = [];
  for (const rm of body.matchAll(/<pcsRow[^>]*>([\s\S]*?)<\/pcsRow>/g)) {
    const row = [[], [], [], []];
    for (const a of rm[1].matchAll(axisRe)) {
      const pos = Number(a[1]);
      titles[pos - 1] = titles[pos - 1] || decode(a[2]);
      row[pos - 4] = labels(a[3]);
    }
    rows.push(row);
  }
  const prev = tables[key];
  if (prev) prev.rows.push(...rows);
  else tables[key] = { s: headAxes[1][1], b: headAxes[2][1], o: headAxes[3][1], d: definition, t: titles, rows };
}
writeDataModule("icd10pcsTables.data.ts", "ICD10PCS_TABLES_JSON", { source: `CMS ICD-10-PCS tables ${pcsVersion}`, tables });
console.log(`CM ${version}: ${chapters.length} chapters, ${chapters.reduce((s, c) => s + c.sections.length, 0)} sections, ${Object.keys(sevenChr).length} 7th-char defs`);
console.log(`PCS ${pcsVersion}: ${Object.keys(tables).length} tables`);
