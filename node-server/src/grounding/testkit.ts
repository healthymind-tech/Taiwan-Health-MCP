/**
 * Shared helpers for the grounding parity tests and scripts (not used at runtime by the tool).
 */
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import type { GroundingIssue, GroundingResult } from "./checkGrounding.js";
import { staticTerminologyNames, type TerminologyCacheFile, type TerminologyNames } from "./terminologyNames.js";

export function fixturePath(name: string): URL {
  return new URL(`./__fixtures__/${name}`, import.meta.url);
}

export function loadFixture<T = any>(name: string): T {
  return JSON.parse(readFileSync(fixturePath(name), "utf8")) as T;
}

/**
 * CARVE-TW parity fixtures (goldens generated by the CARVE reference implementation over the CARVE datasets, the
 * reference terminology cache, the combined validate examples). They are private: the directory is git-ignored and
 * never committed. Tests that need them skip with PRIVATE_SKIP when they are absent; public coverage of the same
 * engines comes from the synthetic tests (syntheticExamples.test.ts and the hand-written records in each test file).
 */
export const PRIVATE_FIXTURE_DIR = "__fixtures__/private";

export function privateFixturePath(name: string): URL {
  return new URL(`./${PRIVATE_FIXTURE_DIR}/${name}`, import.meta.url);
}

export function hasPrivateFixtures(...names: string[]): boolean {
  return names.every((n) => existsSync(fileURLToPath(privateFixturePath(n))));
}

/** Skip reason for tests whose inputs are private CARVE-TW fixtures (false = run). */
export function privateSkip(...names: string[]): string | false {
  return hasPrivateFixtures(...names)
    ? false
    : `private CARVE-TW fixtures absent (src/grounding/${PRIVATE_FIXTURE_DIR}/${names.join(", ")}) — not in git by design`;
}

/** Load a private fixture, or `fallback` when it is absent (callers gate their tests with privateSkip). */
export function loadPrivateFixture<T = any>(name: string, fallback: T): T {
  return hasPrivateFixtures(name) ? (JSON.parse(readFileSync(privateFixturePath(name), "utf8")) as T) : fallback;
}

/** Load a private fixture or throw (scripts: they cannot do anything useful without it). */
export function requirePrivateFixture<T = any>(name: string): T {
  if (!hasPrivateFixtures(name)) throw new Error(`private CARVE-TW fixture missing: src/grounding/${PRIVATE_FIXTURE_DIR}/${name}`);
  return JSON.parse(readFileSync(privateFixturePath(name), "utf8")) as T;
}

/** Static provider over the reference terminology cache (fixture parity). Empty when the private cache is absent. */
export function referenceTerminology(): TerminologyNames {
  return staticTerminologyNames(
    loadPrivateFixture<TerminologyCacheFile>("terminology_cache.json", { codes: {} }),
    "reference terminology_cache.json",
  );
}

