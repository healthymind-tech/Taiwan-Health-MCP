function guessKind(v: unknown): string {
  if (typeof v === "boolean") return "boolean";
  if (typeof v === "number") return "number";
  if (typeof v === "string" && FHIR_DT.test(v)) return "datetime";
  return "string";
}

/** Units of one resource; paths are canonical `Bundle.entry[i].resource.a[0].b`. */
export function enumerateUnits(resource: JsonObject, ei: number): Unit[] {
  const rt = pyStr(resource.resourceType ?? "?");
  const base = `Bundle.entry[${ei}].resource`;
  const out: Unit[] = [];
  const gpathOf = (parts: string[]): string => rt + "." + parts.join(".");

  const walk = (node: unknown, parts: string[], cpath: string): void => {
    if (isDict(node)) {
      const keys = Object.keys(node);
      if ("reference" in node && keys.every((k) => REFERENCE_KEYS.has(k))) return;
      for (const k of keys) {
        const v = node[k];
        if (parts.length === 0 && EXEMPT_ROOT.has(k)) continue;
        if (k === "extension" && parts.length > 0) {
          walkExtensions(node[k], parts, `${cpath}.extension`);
          continue;
        }
        if (k.startsWith("_") || k === "extension" || k === "id") continue;
        if (k === "dataAbsentReason") continue; // handled by the data-absent scan
        visit(v, [...parts, k], `${cpath}.${k}`);
      }
    } else {
      out.push({ path: cpath, gpath: gpathOf(parts), cls: "unclassified", kind: guessKind(node), node, ei });
    }
  };
  const visit = (v: unknown, parts: string[], cpath: string): void => {
    const gp = gpathOf(parts);
    const r = R.get(gp);
    const items: Array<[number | null, unknown]> = Array.isArray(v) ? v.map((x, i) => [i, x] as [number, unknown]) : [[null, v]];
    for (const [i, it] of items) {
      const cp = i === null ? cpath : `${cpath}[${i}]`;
      if (r) out.push({ path: cp, gpath: gp, cls: r[0], kind: r[1], node: it, ei });
      else if (isDict(it)) walk(it, parts, cp);
      else if (gp.endsWith(".display") || gp.endsWith(".system") || gp.endsWith(".version")) continue;
      else out.push({ path: cp, gpath: gp, cls: "unclassified", kind: guessKind(it), node: it, ei });
    }
  };
  /**
   * Extensions (not in the reference, which skips them): a value carried by an extension is a source fact like any
   * other — dates (e.g. PAS extension-diagnosisRecordedDate), quantities and codings are checked; strings are
   * narrative; references / identifiers / booleans / codes are left unclassified (information). Root-level extensions
   * stay exempt (spec §2.2.5), and data-absent-reason is handled by the data-absent scan.
   */
  const walkExtensions = (exts: unknown, parts: string[], cpath: string): void => {
    if (!Array.isArray(exts)) return;
    exts.forEach((ext, i) => {
      if (!isDict(ext)) return;
      const url = typeof ext.url === "string" ? ext.url : "";
      if (url.endsWith("StructureDefinition/data-absent-reason")) return;
      const ep = `${cpath}[${i}]`;
      const eparts = [...parts, "extension"];
      for (const [k, v] of Object.entries(ext)) {
        if (k === "extension") walkExtensions(v, eparts, `${ep}.extension`);
        if (!k.startsWith("value")) continue;
        const gp = gpathOf([...eparts, k]);
        const cp = `${ep}.${k}`;
        if (k === "valueDate" || k === "valueDateTime" || k === "valueInstant") out.push({ path: cp, gpath: gp, cls: "source_fact", kind: "datetime", node: v, ei });
        else if (k === "valueQuantity") out.push({ path: cp, gpath: gp, cls: "source_fact", kind: "quantity", node: v, ei });
        else if (k === "valueCodeableConcept" || k === "valueCoding") out.push({ path: cp, gpath: gp, cls: "coding", kind: "generic", node: v, ei });
        else if (k === "valueString" || k === "valueMarkdown") out.push({ path: cp, gpath: gp, cls: "narrative", kind: "text", node: v, ei });
        else if (!isDict(v) || !("reference" in v)) out.push({ path: cp, gpath: gp, cls: "unclassified", kind: isDict(v) ? "string" : guessKind(v), node: v, ei });
      }
    });
  };
  if (NON_RECORD_RESOURCES.has(rt)) {
    // payer responses / server outcomes are not derived from the record: every element is exempt
    walk(resource, [], base);
    for (const u of out) u.cls = "exempt";
    return out;
  }
  walk(resource, [], base);
  return out;
}

