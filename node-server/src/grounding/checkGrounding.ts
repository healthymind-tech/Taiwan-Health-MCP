/** All `system|code` keys whose authoritative names the engine may need (every dict with a `code`). */
export function collectCodingKeys(bundle: unknown): string[] {
  const keys = new Set<string>();
  const walk = (o: unknown): void => {
    if (Array.isArray(o)) o.forEach(walk);
    else if (isDict(o)) {
      if ("code" in o && (typeof o.code === "string" || typeof o.code === "number")) keys.add(termKey(o.system, o.code));
      for (const v of Object.values(o)) if (typeof v === "object" && v !== null) walk(v);
    }
  };
  walk(bundle);
  return [...keys].sort();
}

export function sourceSha256Prefix(sourceText: string | null | undefined): string {
  return createHash("sha256")
    .update(sourceText ?? "", "utf8")
    .digest("hex")
    .slice(0, 16);
}

/** Resolve the effective mode: explicit, else strict when an evidence map is given, else auto. */
export function resolveMode(mode: GroundingMode | null | undefined, evidenceMap: unknown): GroundingMode {
  return mode ? mode : truthy(evidenceMap) ? "strict" : "auto";
}

function nowMs(): number {
  return performance.now();
}

/**
 * Synchronous core. `terms` must contain the authoritative names for the Bundle's codings
 * (see `collectCodingKeys`); missing keys are treated as unknown codes.
 */
export function checkGroundingSync(
  input: GroundingInput,
  terms: ReadonlyMap<string, TermRecord>,
  opts: { instructionMarkers?: readonly string[]; now?: () => number } = {},
): GroundingResult {
  const clock = opts.now ?? nowMs;
  const t0 = clock();
  const bundle = (isDict(input.bundle) ? input.bundle : {}) as JsonObject;
  const policy = (input.policy ?? {}) as GroundingPolicy;
  const evidenceMap = input.evidence_map;
  const mode = resolveMode(input.mode, evidenceMap);
  const verbosity: GroundingVerbosity = input.verbosity ?? "warnings";
  const markers = input.instruction_markers && input.instruction_markers.length ? input.instruction_markers : opts.instructionMarkers ?? DEFAULT_INSTRUCTION_MARKERS;
  const src = new Source(input.source_text ?? "", input.site_config, markers);
  const refs = new Map<string, JsonObject>();
  for (const e of (Array.isArray(bundle.entry) ? bundle.entry : []) as unknown[]) {
    if (!isDict(e) || !isDict(e.resource)) continue;
    const r = e.resource;
    if (typeof e.fullUrl === "string") refs.set(e.fullUrl, r);
    if (r.resourceType && r.id) refs.set(`${pyStr(r.resourceType)}/${pyStr(r.id)}`, r);
  }
  const ctx: Ctx = { src, terms, refs };
  const rawEntries = (Array.isArray(bundle.entry) ? bundle.entry : truthy(bundle.entry) ? [] : []) as unknown[];
  const entries: JsonObject[] = rawEntries.map((e) => (isDict(e) ? e : {}));
  const issuesByEntry: GroundingIssue[][] = entries.map(() => []);
  const bundleIssues: GroundingIssue[] = [];
  const stats: Stats = {
    units_total: 0,
    units_checked: 0,
    grounded_evidence: 0,
    grounded_auto: 0,
    ungrounded: 0,
    defaults_assumed: 0,
    derived: 0,
    narrative: 0,
    exempt: 0,
  };
  // evidence map -> [entry index, tokens, quotes, original path]
  const ev: Array<[number, Tok[], string[], string]> = [];
  if (Array.isArray(evidenceMap)) {
    for (const item of evidenceMap) {
      if (!isDict(item)) continue;
      const p = item.path;
      const q = "quote" in item ? item.quote : item.quotes;
      const quotes = (Array.isArray(q) ? q : truthy(q) ? [q] : []) as unknown[];
      const ps = typeof p === "string" ? p : "";
      const [ei, toks] = normalizeEvidencePath(ps, bundle);
      if (ei === null || toks === null) {
        bundleIssues.push(issue("warning", "G-EVIDENCE-PATH", ps, `evidence path cannot be resolved in the Bundle: '${pyStr(p)}'`));
        continue;
      }
      ev.push([ei, toks, quotes.map((x) => (typeof x === "string" ? x : pyStr(x))), ps]);
    }
  } else if (isDict(evidenceMap)) {
    for (const [p, q] of Object.entries(evidenceMap)) {
      const [ei, toks] = normalizeEvidencePath(p, bundle);
      if (ei === null || toks === null) {
        bundleIssues.push(issue("warning", "G-EVIDENCE-PATH", p, `evidence path cannot be resolved in the Bundle: '${p}'`));
        continue;
      }
      const qs = (Array.isArray(q) ? q : [q]) as unknown[];
      ev.push([ei, toks, qs.map((x) => (typeof x === "string" ? x : x === null || x === undefined ? "" : pyStr(x))), p]);
    }
  }
  if (!src.structured)
    bundleIssues.push(issue("information", "G-NO-STRUCTURE", "Bundle", "no section headers recognised in the record; section rules are downgraded to warnings"));
  const allUnits: Unit[] = [];
  const usedEv = new Set<number>();
  entries.forEach((e, ei) => {
    const res = (isDict(e.resource) ? e.resource : {}) as JsonObject;
    if (!isDict(e.resource) || !Object.keys(e.resource).length || !truthy(res.resourceType)) {
      // Deviation (spec §2.2.8): report entries that cannot be checked instead of skipping them silently.
      bundleIssues.push(issue("information", "G-UNCLASSIFIED", `Bundle.entry[${ei}]`, "entry has no resource or no resourceType; not checked"));
    }
    const units = enumerateUnits(res, ei);
    allUnits.push(...units);
    const profTails = profileTails(res);
    const fixedCode = profTails.some((t) => FIXED_CODE_PROFILES.has(t));
    for (const u of units) {
      stats.units_total += 1;
      let cls = u.cls;
      if (cls === "exempt" || cls === "site") {
        stats.exempt += 1;
        continue;
      }
      if (cls === "unclassified") {
        if ([".system", ".display", ".version", ".url", ".use"].some((s) => u.gpath.endsWith(s)) || u.kind === "boolean") {
          stats.exempt += 1;
          continue;
        }
        if (u.kind === "datetime") {
          u.cls = cls = "source_fact";
        } else {
          stats.exempt += 1;
          issuesByEntry[ei].push(issue("information", "G-UNCLASSIFIED", u.path, `${describe(u)} is not classified; not checked`));
          continue;
        }
      }
      if (cls === "narrative") {
        stats.narrative += 1;
        const txt = typeof u.node === "string" ? u.node : isDict(u.node) ? u.node.text : "";
        if (truthy(txt)) {
          const cov = coverage(pyStr(txt), src);
          if (cov < 0.5)
            issuesByEntry[ei].push(
              issue("warning", "G-NARRATIVE", u.path, `free text has little overlap with the record (${pyFixed(cov * 100, 0)}%); make sure it only restates the record`),
            );
        }
        continue;
      }
      if (cls === "derived") {
        stats.derived += 1;
        continue;
      }
      if (cls === "workflow_default") {
        let val: unknown = u.node;
        if (isDict(val)) {
          const cs = ccCodings(val);
          val = cs.length ? cs[0].code : null;
        }
        if ((own(WORKFLOW_DEFAULTS, u.gpath) ?? []).some((d) => pyEq(d, val))) {
          stats.defaults_assumed += 1;
          continue;
        }
        // a non-default status is a claim about the record
      }
      if (QUANTITY_KINDS.has(u.kind) && isDict(u.node) && !("value" in u.node)) {
        // Deviation (PAS): a Quantity without a value only carries a unit / package code (e.g. PAS
        // dispenseRequest.quantity with a v3-orderableDrugForm code) — there is no number to ground.
        stats.exempt += 1;
        issuesByEntry[ei].push(issue("information", "G-UNCLASSIFIED", u.path, `${describe(u)} has no value; not checked`));
        continue;
      }
      if (cls === "coding" && (u.gpath === "Observation.code" || u.gpath === "Observation.component.code") && fixedCode) {
        stats.exempt += 1;
        continue;
      }
      stats.units_checked += 1;
      const ut = unitRelTokens(u);
      const quotes: string[] = [];
      ev.forEach(([eei, toks, qs], k) => {
        if (eei === ei && covers(toks, ut)) {
          quotes.push(...qs.filter((q) => q));
          usedEv.add(k);
        }
      });
      checkUnit(ctx, u, quotes, res, mode, issuesByEntry[ei], stats);
    }
    // coherence: an Observation's code and its value must be grounded on a shared line (row / header of the row)
    if (res.resourceType === "Observation") {
      const cu = units.filter((u) => u.gpath === "Observation.code" && u._lines && u._lines.size);
      const vu = units.filter((u) => u.gpath === "Observation.valueQuantity" && u._lines && u._lines.size);
      if (cu.length && vu.length) {
        const shared = [...cu[0]._lines!].some((x) => vu[0]._lines!.has(x));
        const valueLines = [...vu[0]._lines!].filter((j): j is number => j !== null).sort((a, b) => a - b);
        if (!shared && !labelOk(ctx, valueLines.map((j) => src.lines[j].line).join(" "), res))
          issuesByEntry[ei].push(
            issue(
              "error",
              "G-CONTEXT-LABEL",
              cu[0].path,
              `${describe(cu[0])} is grounded on a different line than the value ${describe(vu[0])}; the code must name the measurement whose value is reported`,
            ),
          );
      }
    }
    // identifier systems must come from the site configuration or the profile
    for (const u of units) {
      if (u.kind === "identifier" && isDict(u.node)) {
        const sysu = u.node.system;
        if (truthy(sysu) && !src.siteSystems.has(pyStr(sysu)) && !NO_SITE_SYSTEMS.includes(pyStr(sysu)))
          issuesByEntry[ei].push(
            issue("warning", "G-SYSTEM-NOT-SITE", u.path + ".system", `identifier.system '${pyStr(sysu)}' is neither in the site configuration nor fixed by the profile`),
          );
      }
    }
  });
  ev.forEach(([, , , p], k) => {
    if (!usedEv.has(k))
      bundleIssues.push(issue("information", "G-EVIDENCE-PATH", p, "evidence entry does not cover any checked element (exempt or default element); ignored"));
  });
  dataAbsentScan(entries, issuesByEntry, policy);
  statedAbsenceScan(ctx, entries, allUnits, issuesByEntry);

  // policy: per-rule severity override ("off" drops the rule)
  const applyPolicy = (list: GroundingIssue[]): GroundingIssue[] => {
    const out: GroundingIssue[] = [];
    for (const i of list) {
      const p = policy[i.rule];
      if (p === "off") continue;
      if (p === "error" || p === "warning" || p === "information") out.push({ ...i, severity: p });
      else out.push(i);
    }
    return out;
  };
  const keep = (i: GroundingIssue): boolean =>
    verbosity === "all" ? true : verbosity === "warnings" ? i.severity !== "information" : i.severity === "error";
  const bySev = (a: GroundingIssue, b: GroundingIssue): number => SEV[b.severity] - SEV[a.severity];

  let nErr = 0;
  let nWarn = 0;
  let nInfo = 0;
  const outEntries: GroundingEntryResult[] = entries.map((e, ei) => {
    const all = applyPolicy(issuesByEntry[ei]).sort(bySev);
    for (const i of all) {
      if (i.severity === "error") nErr++;
      else if (i.severity === "warning") nWarn++;
      else nInfo++;
    }
    const r = (isDict(e.resource) ? e.resource : {}) as JsonObject;
    const prof = profileTails(r);
    return {
      fullUrl: (e.fullUrl ?? null) as string | null,
      resourceType: (r.resourceType ?? null) as string | null,
      valid: !all.some((i) => i.severity === "error"),
      profile: prof.length ? prof[0] : "",
      issues: all.filter(keep),
    };
  });
  const bAll = applyPolicy(bundleIssues); // bundle-level issues keep their emission order (reference)
  for (const i of bAll) {
    if (i.severity === "error") nErr++;
    else if (i.severity === "warning") nWarn++;
    else nInfo++;
  }
  const checked = stats.units_checked;
  const summary: GroundingSummary = {
    ...stats,
    errors: nErr,
    warnings: nWarn,
    information: nInfo,
    coverage: checked ? pyRound((stats.grounded_evidence + stats.grounded_auto) / checked, 3) : 1.0,
  };
  const bprof = profileTails(bundle);
  return {
    valid: nErr === 0,
    source: "grounding",
    mode,
    profile: bprof.length ? bprof[0] : "",
    issues: bAll.filter(keep),
    entries: outEntries,
    referenceIssues: [],
    grounding: summary,
    elapsed_ms: pyRound(clock() - t0, 1),
  };
}

/**
 * Grounding check (`fhir_check_grounding`). Pre-fetches authoritative code names through the injected provider,
 * then runs the deterministic core.
 */
export async function checkGrounding(input: GroundingInput, deps: GroundingDeps): Promise<GroundingResult> {
  const clock = deps.now ?? nowMs;
  const t0 = clock();
  const keys = collectCodingKeys(input.bundle);
  const terms = keys.length ? await deps.terminology.lookup(keys) : new Map<string, TermRecord>();
  const out = checkGroundingSync(input, terms, { instructionMarkers: deps.instructionMarkers, now: clock });
  out.elapsed_ms = pyRound(clock() - t0, 1);
  deps.logger?.debug?.("grounding check", {
    sourceSha256: sourceSha256Prefix(input.source_text),
    mode: out.mode,
    valid: out.valid,
    errors: out.grounding.errors,
    warnings: out.grounding.warnings,
    units: out.grounding.units_checked,
    elapsed_ms: out.elapsed_ms,
  });
  return out;
}

/** Provenance block for the MCP response envelope (spec §2.0). Never contains the source text itself. */
export async function groundingProvenance(input: Pick<GroundingInput, "source_text">, deps: Pick<GroundingDeps, "terminology">): Promise<GroundingProvenance> {
  return {
    tool: "fhir_check_grounding",
    toolVersion: GROUNDING_TOOL_VERSION,
    referenceVersion: GROUNDING_REFERENCE_VERSION,
    lexiconVersion: LEXICON_VERSION,
    lexiconSha256: LEXICON_SHA256,
    terminologyVersion: await deps.terminology.version(),
    sourceSha256: sourceSha256Prefix(input.source_text),
  };
}
