/**
 * Deterministic grounding (faithfulness) check for FHIR Bundles — engine behind `fhir_check_grounding`
 * (spec: mcp_proposal/MCP_GROUNDING_SPEC.md §2.0, §2.2).
 *
 * Every source-dependent value in the Bundle (dates, quantities, identifiers, names, doses, frequencies, codes …)
 * must be supported by the clinical record text: either by a verbatim quote in the caller's evidence map
 * (validated) or — in `auto` mode — by text the engine locates itself. Section / negation / historical /
 * instruction / label / stated-absent / data-absent context rules apply. Output issues use the same shape as
 * `fhir_validate_bundle` issues plus `rule` / `source: "grounding"` / evidence fields.
 *
 * TypeScript port of mcp_proposal/reference/grounding_ref.py (reference only); deviations are marked
 * "Deviation" in comments and listed in grounding/README notes of the integration report.
 *
 * Determinism: no LLM, no randomness, no embeddings, no network. Terminology names are pre-fetched through the
 * injected `TerminologyNames` provider; the core then runs synchronously. Privacy: the source text is never
 * logged — only a SHA-256 prefix.
 */
