const RE_SITE_URL = /https?:\/\/[^\s，,；;）)]+/gu;

/** Grounding view of the record: the shared RecordText index plus site systems, record years, clauses and windows. */
export class Source extends RecordText {
  readonly siteSystems: Set<string>;
  readonly years: Set<number>;
  private windowsCache?: number[][];
  private candidateCache?: number[];
  private dateContextCache?: Map<number, [number | null, number, number] | null>;

  constructor(text: string, siteConfig: string | null | undefined, instructionMarkers: readonly string[]) {
    super(text, siteConfig, instructionMarkers);
    this.siteSystems = new Set(this.site.match(RE_SITE_URL) ?? []);
    this.years = new Set(parseDates(this.text).map(([, [y]]) => y).filter((y): y is number => truthy(y)));
  }

  /** Clause around an occurrence: [text from the previous clause delimiter to the occurrence, rest of the line]. */
  clause(occ: Occurrence): [string, string] {
    if (occ.origin !== "record" || occ.li === null) return [occ.line, ""];
    const ln = this.lines[occ.li];
    const s = Math.max(occ.start - ln.start, 0);
    const before = ln.line.slice(0, s);
    let cut = 0;
    for (const m of findAll(CLAUSE_SPLIT, before)) cut = Math.max(cut, m.index + m[0].length);
    return [before.slice(cut), ln.line.slice(s)];
  }

  /**
   * Current-event date context of line i: [line index, date] of the last day-precision date on the nearest line <= i
   * that states one, skipping the conversion target, history sections and dates labelled as a birth date or a past
   * event (出生日期 …, 上次 …). null when no such line precedes.
   */
  governingDateLine(i: number): [number, [number | null, number, number]] | null {
    if (!this.dateContextCache) this.dateContextCache = new Map();
    for (let j = i; j >= 0; j--) {
      let d = this.dateContextCache.get(j);
      if (d === undefined) {
        d = lineContextDate(this.lines[j]);
        this.dateContextCache.set(j, d);
      }
      if (d) return [j, d];
    }
    return null;
  }

  candidateLines(): number[] {
    if (!this.candidateCache) this.candidateCache = this.lines.map((ln, i) => (norm(ln.line) ? i : -1)).filter((i) => i >= 0);
    return this.candidateCache;
  }

  /**
   * Candidate evidence windows for auto-locate, in preference order: each line alone; the line with up to four
   * preceding lines; the line with the first one/two lines of its block (table headers); the line with a
   * document-date line among the first five lines. (Reference `_windows`, including its duplicates.)
   */
  windows(): number[][] {
    if (this.windowsCache) return this.windowsCache;
    const ls = this.candidateLines();
    const W: number[][] = ls.map((i) => [i]);
    const seen = new Set<string>(W.map((w) => w.join(",")));
    const nl = this.lines.length;
    // Deviation: the conversion target 【轉換目標】 is never evidence, so it never contributes header / label / date
    // lines to another line's window either (the reference only judged the window's last line).
    const instr = (j: number): boolean => this.lines[j].section === "instruction";
    for (const i of ls) {
      const b = this.blocks[i];
      const cands: Array<number[] | null> = [[i - 1, i], [i - 2, i], [i - 3, i], [i - 4, i], [b, i], [b, b + 1, i], b > 0 ? [b - 1, i] : null];
      for (const w of cands) {
        if (!w) continue;
        if (!w.every((j) => j >= 0 && j < nl)) continue;
        if (new Set(w).size !== w.length || w[w.length - 1] !== i) continue;
        if (w.slice(0, -1).some(instr)) continue;
        const key = w.join(",");
        if (seen.has(key)) continue;
        const sorted = [...new Set(w)].sort((x, y) => x - y);
        W.push(sorted);
        seen.add(sorted.join(","));
      }
    }
    const heads: number[] = [];
    for (let j = 0; j < Math.min(5, nl); j++) if (parseDates(this.lines[j].line).length) heads.push(j);
    for (const i of ls) for (const h of heads) if (h !== i && !instr(h) && !(h > i && instr(i))) W.push([h, i].sort((x, y) => x - y));
    this.windowsCache = W;
    return W;
  }
}

const CONTEXT_DATE_SKIP_SECTIONS = new Set(["instruction", "site_config", "history", "family_history"]);
const RE_FIELD_SPLIT = /[，,；;。|│]/u;

/** Last current-event date of a line (see Source.governingDateLine), or null. */
function lineContextDate(ln: SourceLine): [number | null, number, number] | null {
  if (CONTEXT_DATE_SKIP_SECTIONS.has(ln.section)) return null;
  const t = nfkc(ln.line);
  let best: [number | null, number, number] | null = null;
  let prevEnd = 0;
  for (const pd of [...parseDatesPos(ln.line)].sort((a, b) => a.start - b.start)) {
    const [prec, [y, m, d]] = pd.date;
    const segs = t.slice(prevEnd, pd.start).split(RE_FIELD_SPLIT);
    const label = segs[segs.length - 1];
    prevEnd = pd.end;
    if (prec !== "day" && prec !== "md") continue;
    if (BIRTH_LABELS.some((b) => label.includes(b)) || HIST_CUES.some((c) => label.includes(c))) continue;
    best = [prec === "day" ? y : null, m!, d!];
  }
  return best;
}

// ============================================================================================= terminology helpers
interface Ctx {
  src: Source;
  terms: ReadonlyMap<string, TermRecord>;
  /** Bundle resources by `Type/id` and fullUrl (to follow references such as PAS extension-requestedService). */
  refs?: ReadonlyMap<string, JsonObject>;
}

function ccCodings(node: unknown): JsonObject[] {
  if (isDict(node)) {
    if ("coding" in node) {
      const c = node.coding;
      return Array.isArray(c) ? c.filter(isDict) : [];
    }
    if ("code" in node && "system" in node) return [node];
  }
  return [];
}

function authoritativeNames(ctx: Ctx, codings: JsonObject[]): [string[], boolean] {
  const names: string[] = [];
  let foundAny = false;
  for (const c of codings) {
    const rec = ctx.terms.get(termKey(c.system, c.code));
    if (rec && rec.found) {
      foundAny = true;
      names.push(...rec.names);
    }
    const code = pyStr(or(c.code, ""));
    if (code) names.push("__CODE__" + code);
  }
  return [names, foundAny];
}

function codingScore(ctx: Ctx, quote: string, node: unknown): [number, string | null, boolean] {
  const codings = ccCodings(node);
  const [names, auth] = authoritativeNames(ctx, codings);
  const qn = nfkc(quote);
  let best = 0;
  let bestName: string | null = null;
  for (const n of names) {
    if (n.startsWith("__CODE__")) {
      const c = n.slice(8).toLowerCase();
      if (cpLen(c) >= 3 && new RegExp("(?<![a-z0-9.])" + escapeRe(c) + "(?![a-z0-9])", "u").test(qn)) return [1.0, c, true];
      continue;
    }
    const s = nameSimilarity(quote, n);
    if (s > best) {
      best = s;
      bestName = n;
    }
  }
  if (!auth) {
    // fall back to the model's own display / text (cannot produce an error)
    const own: string[] = codings.filter((c) => truthy(c.display)).map((c) => pyStr(c.display));
    if (isDict(node) && truthy(node.text)) own.push(pyStr(node.text));
    for (const n of own) {
      const s = nameSimilarity(quote, n);
      if (s > best) {
        best = s;
        bestName = n;
      }
    }
  }
  return [best, bestName, auth];
}

function profileTails(res: JsonObject): string[] {
  const meta = or(res.meta, {}) as unknown;
  const prof = isDict(meta) ? or(meta.profile, []) : [];
  return (Array.isArray(prof) ? prof : []).map((p) => {
    const s = pyStr(p);
    const i = s.lastIndexOf("/");
    return i >= 0 ? s.slice(i + 1) : s;
  });
}

function labelsForObs(ctx: Ctx, resource: JsonObject, comp: JsonObject | null): [string[], string[]] {
  const node = comp && truthy(comp) ? comp.code : resource.code;
  const labels: string[] = [];
  for (const tail of profileTails(resource)) labels.push(...(own(VITAL_LABELS, own(PROFILE_LABEL_CODE, tail) ?? "") ?? []));
  for (const c of ccCodings(node)) labels.push(...(own(VITAL_LABELS, pyStr(c.code)) ?? []));
  const [names] = authoritativeNames(ctx, ccCodings(node));
  const outNames = names.filter((n) => !n.startsWith("__CODE__"));
  if (isDict(node) && truthy(node.text)) outNames.push(pyStr(node.text));
  return [labels, outNames];
}

const LABEL_RE_CACHE = new Map<string, RegExp>();
function labelRe(lb: string): RegExp {
  let r = LABEL_RE_CACHE.get(lb);
  if (!r) {
    const last = Array.from(lb).pop() ?? "";
    r = new RegExp("(?<![a-z])" + escapeRe(lb) + (isAlpha(last) ? "(?![a-z])" : ""), "u");
    LABEL_RE_CACHE.set(lb, r);
  }
  return r;
}

/** PAS Claim.supportingInfo[i]: labels from the category code table plus the category / code names. */
function labelsForSupportingInfo(ctx: Ctx, si: JsonObject): [string[], string[]] {
  const labels: string[] = [];
  const names: string[] = [];
  for (const key of ["category", "code"]) {
    const node = si[key];
    for (const c of ccCodings(node)) {
      labels.push(...(own(SUPPORTING_INFO_LABELS, pyStr(c.code)) ?? []));
      if (truthy(c.display)) names.push(pyStr(c.display));
    }
    const [auth] = authoritativeNames(ctx, ccCodings(node));
    names.push(...auth.filter((n) => !n.startsWith("__CODE__")));
    if (isDict(node) && truthy(node.text)) names.push(pyStr(node.text));
  }
  return [labels, names];
}

function labelOk(ctx: Ctx, quote: string, resource: JsonObject, comp: JsonObject | null = null, si: JsonObject | null = null): boolean {
  const [labels, names] = si ? labelsForSupportingInfo(ctx, si) : labelsForObs(ctx, resource, comp);
  const q = nfkc(quote);
  for (const lb of labels) if (labelRe(lb).test(q)) return true;
  for (const n of names) if (n && nameSimilarity(quote, n) >= 0.5) return true;
  return false;
}

// ============================================================================================= value checkers
type Status = string; // ok | ok_* | mismatch | precision | weak | unverifiable | context_label
type CheckResult = [Status, string];

/** Python `d.get(k, default)` (a present-but-null key yields null, not the default). */
function pget(o: unknown, k: string, def: unknown): unknown {
  return isDict(o) && Object.prototype.hasOwnProperty.call(o, k) ? o[k] : def;
}

/** Own-property lookup (never hits Object.prototype for keys such as "constructor"). */
function own<T>(o: Record<string, T>, k: string): T | undefined {
  return Object.prototype.hasOwnProperty.call(o, k) ? o[k] : undefined;
}

const pad2 = (n: number): string => String(n).padStart(2, "0");
const fmtVal = (v: unknown): string => pyStr(v);

function joinQ(quotes: string[]): string {
  return quotes.join(" ");
}

type Offset = number | { months: number };

const RE_DUR_DAYS = pyRe(String.raw`(?<![\d.])(\d{1,2})\s*(天|days?)(?!前|份|後)`, "g");
const RE_DUR_MONTHS = pyRe(String.raw`(?<![\d.])(\d{1,2})\s*(個月|months?)(?!前|份|後)`, "g");
const RE_DUR_HOURS = pyRe(String.raw`(?<![\d.])(\d{1,2})\s*(小時|hours?|hrs?)`, "g");
const RE_REL_TIME = pyRe(String.raw`(\d+)\s*(分鐘|minutes?|mins?|小時|hours?|hrs?)\s*(後|later|after|前|ago)?`, "g");
const TIME_RE_ONE = new RegExp(TIME_RE.source, "u");

/** '右小腿紅腫熱痛 3 天' / '咳嗽 5 天' / 'x 2 days' in a complaint -> onset offset -N and -(N-1) days. */
function durationOffsets(qtxt: string): Offset[] {
  const out: Offset[] = [];
  const t = nfkc(qtxt);
  for (const m of findAll(RE_DUR_DAYS, t)) {
    const n = parseInt(m[1], 10);
    out.push(-n, -(n - 1));
  }
  for (const m of findAll(RE_DUR_MONTHS, t)) out.push({ months: -parseInt(m[1], 10) });
  for (const _m of findAll(RE_DUR_HOURS, t)) out.push(0, -1); // an onset N hours before arrival may fall on the previous day
  return out;
}

/** -> [{date: time written right after it}, {times not attached to a date}] ('2026-09-18 22:40 … 2026-09-19 02:15'). */
function timePairs(quotes: string[]): [Map<string, string>, Set<string>] {
  const pairs = new Map<string, string>();
  const pairedPos: Array<[string, number]> = [];
  const free = new Set<string>();
  for (const q of quotes) {
    const t = nfkc(q);
    for (const [rx, kind] of DATE_PATTERNS.slice(0, 5)) {
      for (const m of findAll(rx, t)) {
        const g = m.slice(1).filter((x) => x !== undefined).map((x) => parseInt(x, 10));
        if ((kind === "roc" && !(g[0] >= 1 && g[0] <= 200)) || (kind === "west" && !(g[0] >= 1900 && g[0] <= 2100)) || g.length < 3) continue;
        const y = kind === "roc" ? g[0] + 1911 : g[0];
        const end = m.index + m[0].length;
        const rest = t.slice(end, end + 14);
        const mt = TIME_RE_ONE.exec(rest);
        if (mt && mt.index <= 3) {
          const k = `${y}-${g[1]}-${g[2]}`;
          if (!pairs.has(k)) pairs.set(k, `${parseInt(mt[1], 10)}:${parseInt(mt[2], 10)}`);
          pairedPos.push([q, end + mt.index]);
        }
      }
    }
    for (const mt of findAll(TIME_RE, t)) {
      if (!pairedPos.some(([qq, pos]) => qq === q && Math.abs(pos - mt.index) <= 1)) free.add(`${parseInt(mt[1], 10)}:${parseInt(mt[2], 10)}`);
    }
  }
  return [pairs, free];
}

function chkDatetime(ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const v = parseFhirDatetime(unit.node);
  if (v === null) return ["mismatch", `value '${fmtVal(unit.node)}' is not a FHIR date/dateTime`];
  const qtxt = joinQ(quotes);
  const dates = parseDates(qtxt);
  const vprec = v.d ? "day" : v.m ? "month" : "year";
  let okDate = false;
  let precIssue = false;
  for (const [prec, [y, m, d]] of dates) {
    if (prec === "md") {
      if (vprec === "day" && m === v.m && d === v.d && ctx.src.years.has(v.y)) {
        okDate = true;
        break;
      }
      continue;
    }
    if (y !== v.y) continue;
    if (vprec === "year") {
      okDate = true;
      break;
    }
    if (m !== v.m) {
      if (prec === "year") precIssue = true;
      continue;
    }
    if (vprec === "month") {
      okDate = true;
      break;
    }
    if (prec === "day" && d === v.d) {
      okDate = true;
      break;
    }
    if (prec === "month" || prec === "year") precIssue = true;
  }
  let derived = false;
  if (!okDate && vprec === "day") {
    const offs: Offset[] = [...relativeOffsets(qtxt), ...durationOffsets(qtxt)];
    for (const [prec, [y, m, d]] of dates) {
      if (prec !== "day" || !offs.length) continue;
      for (const o of offs) {
        if (typeof o === "object") {
          let mm = m! + o.months;
          const yy = y! + floorDiv(mm - 1, 12);
          mm = pyMod(mm - 1, 12) + 1;
          const dd = d! > 28 ? Math.min(d!, 28) : d!;
          if (validDate(yy, mm, dd) && yy === v.y && mm === v.m && dd === v.d) okDate = derived = true;
          continue;
        }
        const [ty, tm, td] = addDays(y!, m!, d!, o);
        if (ty === v.y && tm === v.m && td === v.d) okDate = derived = true;
      }
    }
  }
  if (!okDate) {
    if (precIssue) return ["precision", `evidence states the date less precisely than the value '${fmtVal(unit.node)}'`];
    const got = dates.map(([, [y, m, d]]) => `${pyStr(y)}-${m ? m : "??"}-${d ? d : "??"}`).join(", ") || "no date";
    return ["mismatch", `value '${fmtVal(unit.node)}' does not match the date(s) in the evidence (${got}; ROC years converted)`];
  }
  if (v.hh !== null) {
    const times = parseTimes(qtxt).map(([h, mi]) => `${h}:${mi}`);
    const [pairs, free] = timePairs(quotes);
    const vt = `${v.hh}:${v.mi}`;
    const vd = `${v.y}-${v.m}-${v.d}`;
    if (times.includes(vt) && !free.has(vt) && pairs.get(vd) !== vt && [...pairs.values()].some((t) => t === vt)) {
      const other = [...pairs.entries()].find(([, t]) => t === vt)![0].split("-").map(Number);
      return [
        "mismatch",
        `in the evidence ${pad2(v.hh)}:${pad2(v.mi!)} belongs to ${other[0]}-${pad2(other[1])}-${pad2(other[2])}, not to ${v.y}-${pad2(v.m!)}-${pad2(v.d!)}`,
      ];
    }
    const baseTimes = [...times];
    for (const m of findAll(RE_REL_TIME, nfkc(qtxt))) {
      const n = parseInt(m[1], 10) * ("小h".includes(m[2][0]) ? 60 : 1);
      const add = ["後", "later", "after"].includes(m[3] ?? "") ? n : -n; // 'N 小時' in a complaint = onset N hours before
      for (const bt of baseTimes) {
        const [h, mi] = bt.split(":").map(Number);
        const tot = h * 60 + mi + add;
        times.push(`${pyMod(floorDiv(tot, 60), 24)}:${pyMod(tot, 60)}`);
      }
    }
    if (!times.includes(vt)) {
      if (ADMIN_TIMESTAMPS.has(unit.gpath))
        return ["ok_admintime", `time of day ${pad2(v.hh)}:${pad2(v.mi!)} is not stated in the evidence (record-keeping timestamp; date matches)`];
      return ["precision", `value '${fmtVal(unit.node)}' has a time of day ${pad2(v.hh)}:${pad2(v.mi!)} that the evidence does not state`];
    }
  }
  if (v.tz_converted && v.tz_converted !== "Z") return ["ok_tz", `time zone ${v.tz_converted} converted to +08:00 for comparison`];
  return derived ? ["ok_derived", "date derived from a relative expression in the evidence"] : ["ok", ""];
}

const RE_COMPONENT_IDX = /\.component\[(\d+)\]/u;
const RE_SUPPORTING_INFO_IDX = /\.supportingInfo\[(\d+)\]/u;
const RE_BP_PAIR = /(\d{2,3})\s*\/\s*(\d{2,3})/gu;

function chkQuantity(ctx: Ctx, unit: Unit, quotes: string[], res: JsonObject, obsLabel = false): CheckResult {
  const node = unit.node;
  if (!isDict(node) || !("value" in node)) return ["mismatch", "Quantity without value"];
  const qtxt = joinQ(quotes);
  let nums = numbersWithUnits(qtxt);
  const vunit = or(node.code, node.unit) as unknown;
  let comp: JsonObject | null = null;
  const mc = RE_COMPONENT_IDX.exec(unit.path);
  if (mc) {
    const comps = or(res.component, []) as unknown;
    const c = Array.isArray(comps) ? comps[parseInt(mc[1], 10)] : undefined;
    comp = isDict(c) ? c : c === undefined || c === null ? null : ({} as JsonObject);
  }
  const bp = findAll(RE_BP_PAIR, nfkc(qtxt)).map((m) => [Number(m[1]), Number(m[2])] as [number, number]);
  if (unit._auto && quotes.length > 1) nums = numbersWithUnits(quotes[quotes.length - 1]); // the number must be on the value line
  let cands: NumberWithUnit[] = nums.filter((n) => sameNumber(n[1], node.value));
  let converted = false;
  if (!cands.length && truthy(vunit)) {
    for (const n of nums) {
      const f = CONVERT.get(`${n[2]}|${canonUnit(vunit)}`);
      if (f && Math.abs(n[1] * f - pyFloat(node.value)) < 1e-6) {
        cands = [n];
        converted = true;
        break;
      }
    }
  }
  if (comp !== null && bp.length) {
    const ccodes = new Set(ccCodings(comp.code).map((c) => pyStr(c.code)));
    if (ccodes.has("8480-6")) {
      if (bp.some(([s]) => sameNumber(s, node.value))) cands = cands.length ? cands : [[null, pyFloat(node.value), null, ""]];
      else if (cands.length) return ["mismatch", `systolic value ${fmtVal(node.value)} is not the first number of the blood-pressure pair in the evidence`];
    }
    if (ccodes.has("8462-4")) {
      if (bp.some(([, d]) => sameNumber(d, node.value))) cands = cands.length ? cands : [[null, pyFloat(node.value), null, ""]];
      else if (cands.length) return ["mismatch", `diastolic value ${fmtVal(node.value)} is not the second number of the blood-pressure pair in the evidence`];
    }
  }
  if (!cands.length) {
    const got = nums.slice(0, 6).map((n) => pyStrip(n[3])).join(", ") || "no number";
    return ["mismatch", `value ${fmtVal(node.value)} ${pyStr(or(node.unit, ""))} not found in the evidence (numbers there: ${got})`];
  }
  let si: JsonObject | null = null;
  const msi = RE_SUPPORTING_INFO_IDX.exec(unit.path);
  if (msi) {
    const sis = or(res.supportingInfo, []) as unknown;
    const x = Array.isArray(sis) ? sis[parseInt(msi[1], 10)] : undefined;
    si = isDict(x) ? x : null;
  }
  if (obsLabel && !labelOk(ctx, qtxt, res, comp, si)) return ["context_label", "evidence contains the number but not the measurement it belongs to (label / analyte name missing)"];
  if (truthy(node.comparator) && !cands.some((c) => truthy(c[0]))) return ["weak", `comparator '${pyStr(node.comparator)}' not stated in the evidence`];
  const units = cands.map((c) => c[2]).filter((u): u is string => truthy(u));
  if (converted) return ["ok_converted", `value converted from ${pyStrip(cands[0][3])} ${pyStr(cands[0][2])} to ${fmtVal(node.value)} ${pyStr(vunit)}`];
  if (units.length && truthy(vunit) && !units.some((u) => unitsCompatible(u, vunit)) && !units.some((u) => unitsCompatible(u, node.unit)))
    return ["mismatch", `unit '${pyStr(vunit)}' is not compatible with the unit in the evidence ('${units[0]}')`];
  if (!units.length && truthy(vunit)) return ["ok_nounit", `evidence states no unit for ${fmtVal(node.value)}`];
  return ["ok", ""];
}

function chkDose(_ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const node = unit.node;
  if (!isDict(node) || !("value" in node)) return ["mismatch", "dose without value"];
  const nums = numbersWithUnits(joinQ(quotes));
  const cands = nums.filter((n) => sameNumber(n[1], node.value));
  if (!cands.length) return ["mismatch", `dose ${fmtVal(node.value)} ${pyStr(or(node.unit, ""))} not found in the evidence`];
  const vunit = or(node.code, node.unit) as unknown;
  const units = cands.map((c) => c[2]).filter((u): u is string => truthy(u));
  if (units.length && truthy(vunit) && !units.some((u) => unitsCompatible(u, vunit) || unitsCompatible(u, node.unit)))
    return ["mismatch", `dose unit '${pyStr(or(node.unit, vunit))}' differs from the evidence ('${units[0]}')`];
  return ["ok", ""];
}

const PERIOD_DAYS: Record<string, number> = { h: 1 / 24, d: 1, wk: 7, mo: 30, min: 1 / 1440 };

/** [per-day frequency | "conflict" | null, whens, codes, perDayIsFloat]. */
function timingSignature(node: unknown): [PerDay | "conflict" | null, Set<string>, string[], boolean] {
  let perDay: PerDay | null = null;
  let isFloat = false;
  const whens = new Set<string>();
  const codes: string[] = [];
  if (!isDict(node)) return [null, whens, codes, false];
  for (const c of ccCodings(node.code)) codes.push(pyStr(or(c.code, "")));
  if (isDict(node.code) && truthy(node.code.text)) codes.push(pyStr(node.code.text));
  for (const c of codes) {
    const k = nfkc(c).replace(/ /g, "");
    if (Object.prototype.hasOwnProperty.call(FREQ_CODES, k)) {
      perDay = FREQ_CODES[k][0];
      isFloat = typeof perDay === "number" && !Number.isInteger(perDay);
      const w = FREQ_CODES[k][1];
      if (w) whens.add(w);
      break;
    }
  }
  const rp = or(node.repeat, {}) as unknown;
  if (isDict(rp)) {
    if (truthy(rp.frequency) && truthy(rp.period) && truthy(rp.periodUnit)) {
      const days = own(PERIOD_DAYS, pyStr(rp.periodUnit));
      if (days) {
        const pdv = pyRound(pyFloat(rp.frequency) / (pyFloat(rp.period) * days), 3);
        if (perDay !== null && perDay !== "once" && Math.abs(pdv - perDay) > 0.01) return ["conflict", whens, codes, false];
        perDay = pdv;
        isFloat = true;
      }
    }
    const when = or(rp.when, []) as unknown;
    if (Array.isArray(when)) for (const w of when) whens.add(pyStr(w));
  }
  if (perDay === null && whens.has("HS")) {
    perDay = 1;
    isFloat = false;
  }
  return [perDay, whens, codes, isFloat];
}

function chkTiming(ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const [perDay, , codes, isFloat] = timingSignature(unit.node);
  if (perDay === "conflict") return ["mismatch", "timing.code and timing.repeat describe different frequencies"];
  if (perDay === null) {
    // Deviation (PAS / NHI frequency codes such as 1W3D, Q4WD1, AC1H that have no per-day signature): the reference
    // accepted any text; we require the code itself or one of its authoritative names to be written in the evidence.
    const node = unit.node;
    const ccs = isDict(node) ? ccCodings(node.code) : [];
    const [names] = authoritativeNames(ctx, ccs);
    const named = names.filter((n) => !n.startsWith("__CODE__"));
    // Deviation (lexicon 0.4.0, issues v2): an as-needed timing (NHI code PRN, or a code / text / authoritative name
    // that says 'as needed' / 需要時 / 必要時 …) is matched on meaning, not on its literal wording: the evidence must
    // state as-needed use in any PRN phrasing of the lexicon (record 'PO PRN' grounds timing.code.text 'as needed',
    // record '視需要服用' grounds code PRN '需要時使用'). A frequency written with it ('q4h PRN') must match too.
    if ([...codes, ...named].some((c) => statesPrn(c))) {
      const qt = joinQ(quotes);
      if (!statesPrn(qt)) return ["mismatch", `as-needed (PRN) timing ${codes.join(", ")} is not stated in the evidence`];
      const want = freqSignatures(codes.join(" "));
      if (want.size) {
        const have = freqSignatures(qt);
        const hit = [...want].some((w) => have.has(w) || [...have].some((h) => typeof h === "number" && typeof w === "number" && Math.abs(h - w) < 0.01));
        if (!hit) return ["mismatch", `frequency of the as-needed timing ${codes.join(", ")} does not match the evidence`];
      }
      return ["ok", ""];
    }
    const cands = [...codes, ...named].map((c) => norm(c)).filter((c) => c.length >= 2);
    if (!cands.length) return ["ok_noinfo", ""];
    const qn = norm(joinQ(quotes));
    if (cands.some((c) => qn.includes(c))) return ["ok", ""];
    return ["mismatch", `frequency ${codes.join(", ")} is not stated in the evidence`];
  }
  const desc = codes.join(", ") || (typeof perDay === "number" ? (isFloat && Number.isInteger(perDay) ? `${perDay}.0` : pyNum(perDay)) : perDay);
  const sig = freqSignatures(joinQ(quotes));
  if (!sig.size) return ["mismatch", `evidence states no administration frequency (value: ${desc})`];
  if (sig.has(perDay) || [...sig].some((x) => typeof x === "number" && typeof perDay === "number" && Math.abs(x - perDay) < 0.01)) return ["ok", ""];
  return ["mismatch", `frequency ${desc}/day does not match the evidence`];
}

const RE_DURATION = pyRe(String.raw`(\d+)\s*(天|日|days?|d\b|週|周|weeks?|wks?|個月|months?)`, "g");

function chkDuration(_ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const node = unit.node;
  if (!isDict(node) || !("value" in node)) return ["mismatch", "duration without value"];
  const u = canonUnit(or(or(node.code, node.unit), "d"));
  const mult = own({ d: 1, wk: 7, mo: 30, h: 1 / 24 } as Record<string, number>, u ?? "") ?? 1;
  const days = pyFloat(node.value) * mult;
  const t = nfkc(joinQ(quotes));
  const found: number[] = [];
  for (const m of findAll(RE_DURATION, t)) {
    const n = parseInt(m[1], 10);
    const w = m[2];
    found.push(n * ("週周w".includes(w[0]) ? 7 : "個m".includes(w[0]) ? 30 : 1));
  }
  if (found.some((f) => Math.abs(f - days) < 1e-6)) return ["ok", ""];
  return ["mismatch", `duration ${fmtVal(node.value)} ${pyStr(or(node.unit, u))} not stated in the evidence (found: ${found.length ? "[" + found.join(", ") + "]" : "none"})`];
}

function chkIdentifier(_ctx: Ctx, unit: Unit, quotes: string[], res: JsonObject): CheckResult {
  const node = unit.node;
  if (!isDict(node) || !truthy(node.value)) return ["mismatch", "identifier without value"];
  const value = pyStr(node.value);
  const v = norm(value);
  const qn = norm(joinQ(quotes));
  if (!qn.includes(v)) return ["mismatch", `identifier value '${value}' does not occur in the evidence`];
  const tcodes = new Set(ccCodings(node.type).map((c) => pyStr(c.code)));
  const ql = nfkc(joinQ(quotes));
  if (res.resourceType === "Patient") {
    const encLabel = ID_LABELS.encounter.some((l) => ql.includes(l));
    const mrLabel = ID_LABELS.mrn.some((l) => ql.includes(l));
    const sys = typeof node.system === "string" ? node.system : "";
    if ((tcodes.has("MR") || (truthy(node.system) && sys.toLowerCase().includes("mrn"))) && encLabel && !mrLabel)
      return ["context_label", `identifier '${value}' is labelled as an encounter/admission number in the record, not a chart number (MRN)`];
    if (tcodes.has("NNxxx") || node.system === "http://www.moi.gov.tw") {
      if (!TW_ID_RE.test(v)) return ["mismatch", `'${value}' does not have the Taiwan national ID format`];
      if (!twIdChecksumOk(value)) return ["weak", `'${value}' fails the national-ID check digit`];
    }
  }
  return ["ok", ""];
}

function chkName(_ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const node = unit.node;
  if (!isDict(node)) return ["mismatch", "HumanName expected"];
  const qn = norm(joinQ(quotes));
  const parts: string[] = [];
  if (truthy(node.text)) parts.push(pyStr(node.text));
  const fam = node.family;
  const givArr = or(node.given, []) as unknown;
  const giv = Array.isArray(givArr) ? givArr.map(pyStr).join(" ") : pyStr(givArr);
  if (truthy(fam) || truthy(giv)) parts.push(pyStr(or(fam, "")) + giv);
  if (!parts.length) return ["mismatch", "HumanName has no text/family/given"];
  for (const p of parts) {
    if (norm(p) && !qn.includes(norm(p)) && !qn.includes(norm(p.replace(/ /g, "")))) {
      if (truthy(fam) && truthy(giv) && qn.includes(norm(giv + pyStr(fam)))) continue; // Latin names: 'given family'
      return ["mismatch", `name '${p}' does not occur in the evidence`];
    }
  }
  return ["ok", ""];
}

function chkGender(_ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const g = gendersIn(joinQ(quotes));
  const v = unit.node;
  if (typeof v === "string" && g.has(v) && g.size === 1) return ["ok", ""];
  if (typeof v === "string" && g.has(v)) return ["weak", "evidence mentions both sexes"];
  return ["mismatch", `gender '${pyStr(v)}' not stated in the evidence`];
}

function chkString(_ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const v = norm(pyStr(unit.node));
  if (v && norm(joinQ(quotes)).includes(v)) return ["ok", ""];
  return ["mismatch", `'${pyStr(unit.node)}' does not occur in the evidence`];
}

const RE_PLAIN_NUM = /\d+(?:\.\d+)?/gu;
function chkNumber(_ctx: Ctx, unit: Unit, quotes: string[]): CheckResult {
  const t = nfkc(joinQ(quotes));
  const nums = [...(t.match(RE_PLAIN_NUM) ?? []).map(Number), ...Array.from(t).filter((c) => c in CN_NUM).map((c) => CN_NUM[c])];
  if (typeof unit.node === "boolean") return ["ok", ""];
  if (nums.some((n) => sameNumber(n, unit.node))) return ["ok", ""];
  return ["mismatch", `number ${pyStr(unit.node)} not stated in the evidence`];
}

