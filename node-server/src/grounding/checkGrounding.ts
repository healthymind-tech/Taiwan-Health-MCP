  "G-CODING-WEAK": "code-invalid",
  "G-CODING-UNVERIFIABLE": "informational",
  "G-DATA-ABSENT": "incomplete",
  "G-STATED-ABSENT": "business-rule",
  "G-EVIDENCE-PATH": "not-found",
  "G-AUTO-LOCATED": "informational",
  "G-DEFAULT-ASSUMED": "informational",
  "G-NARRATIVE": "informational",
  "G-UNIT-NOT-STATED": "value",
  "G-VALUE-WEAK": "value",
